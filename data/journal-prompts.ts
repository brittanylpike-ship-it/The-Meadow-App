const usedIndices: Partial<Record<Mood, Set<number>>> = {};

export function getPrompt(mood: Mood): string {
  const prompts = JOURNAL_PROMPTS[mood];
  if (!usedIndices[mood]) {
    usedIndices[mood] = new Set();
  }

  const used = usedIndices[mood]!;
  if (used.size >= prompts.length) {
    used.clear();
  }

  let index: number;
  do {
    index = Math.floor(Math.random() * prompts.length);
  } while (used.has(index));

  used.add(index);
  return prompts[index];
}
